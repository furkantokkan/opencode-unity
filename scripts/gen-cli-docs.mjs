#!/usr/bin/env node
// Generates docs/cli-reference.md from the CLI registry and the support matrix (spec 19, 21.1; build
// step S19).
//
// The registry in src/cli/registry.js is the table the parser and `--help` read, and src/core/tiers.json
// is the table the platform gate reads, so the page cannot describe a flag, an exit code or a tier the
// CLI does not have. A command whose module is not in this build is listed as such rather than left out.
// CI runs this and fails when the committed page differs.
//
// Exit codes: 0 written or already current, 1 --check found a difference, 2 usage or runtime error.
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { EXIT_CODES, getExitCodeInfo } from '../src/cli/exit-codes.js';
import { HELP_GROUPS, formatUsage } from '../src/cli/help.js';
import { COMMANDS, GLOBAL_OPTIONS, isCommandAvailable } from '../src/cli/registry.js';
import { CLI_NAME } from '../src/cli/version.js';
import { loadTiers } from '../src/core/platform.js';

export const OUTPUT_URL = new URL('../docs/cli-reference.md', import.meta.url);
const OUTPUT_NAME = 'docs/cli-reference.md';

const HEADER = `<!-- Generated by scripts/gen-cli-docs.mjs from src/cli/registry.js and src/core/tiers.json. Do not edit by hand. -->

# CLI reference

Every command, flag and exit code of \`${CLI_NAME}\`, taken from the same table the argument parser and
\`${CLI_NAME} help\` read. \`${CLI_NAME} help <command>\` prints the same information at the terminal.

With \`--json\`, every command prints one JSON envelope on standard output and its human text on standard
error: \`{ ok, command, exitCode, code, message, data, warnings, version }\`, where \`ok\` is true exactly
when \`exitCode\` is 0 and \`code\` is a stable snake_case identifier.
`;

/** @typedef {import('../src/cli/registry.js').CommandSpec} CommandSpec */
/** @typedef {import('../src/cli/registry.js').OptionSpec} OptionSpec */
/** @typedef {import('../src/cli/registry.js').PositionalSpec} PositionalSpec */

/**
 * @typedef {object} RenderInput
 * @property {readonly CommandSpec[]} [commands]
 * @property {readonly OptionSpec[]} [globalOptions]
 * @property {(command: CommandSpec) => boolean} [isAvailable]
 * @property {Record<string, any>} [tiers]
 */

/**
 * @param {RenderInput} [input]
 * @returns {string}
 */
export function renderCliReference({ commands = COMMANDS, globalOptions = GLOBAL_OPTIONS, isAvailable = isCommandAvailable, tiers = loadTiers() } = {}) {
  const lines = [HEADER];
  lines.push('## Commands', '');
  for (const group of HELP_GROUPS) {
    const members = commands.filter((command) => command.group === group.id);
    if (members.length === 0) continue;
    lines.push(`- ${group.title}: ${members.map((command) => `[\`${command.name}\`](#${command.name})`).join(', ')}`);
  }
  lines.push('');

  lines.push('## Global options', '', 'Every command accepts these.', '');
  lines.push(...optionTable(globalOptions), '');

  lines.push('## Exit codes', '', 'A released exit code never changes meaning.', '');
  lines.push('| Exit | Name | Default `code` | Meaning |', '|---|---|---|---|');
  for (const info of EXIT_CODES) lines.push(`| ${info.exitCode} | \`${info.name}\` | \`${info.code}\` | ${escapeCell(escapeProse(info.summary))} |`);
  lines.push('');

  lines.push(...renderSupportMatrix(commands, tiers));

  for (const group of HELP_GROUPS) {
    for (const command of commands.filter((entry) => entry.group === group.id)) {
      lines.push(...renderCommand(command, { available: isAvailable(command) }));
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/**
 * @param {CommandSpec} command
 * @param {{ available: boolean }} options
 * @returns {string[]}
 */
function renderCommand(command, { available }) {
  const lines = [`## ${command.name}`, ''];
  lines.push('```text', formatUsage(command), '```', '');
  lines.push(escapeProse(`${command.summary}.${command.description ? ` ${command.description}` : ''}`), '');
  if (!available) lines.push(`**Not available in this build.** Running it exits 8 with the code \`command_not_available\`.`, '');
  if (command.positionals.length > 0) lines.push(...positionalTable(command.positionals), '');
  if (command.options.length > 0) lines.push(...optionTable(command.options), '');
  for (const subcommand of command.subcommands ?? []) {
    lines.push(`### ${command.name} ${subcommand.name}`, '');
    lines.push('```text', formatUsage(command, subcommand), '```', '');
    lines.push(escapeProse(`${subcommand.summary}.`), '');
    if (subcommand.positionals.length > 0) lines.push(...positionalTable(subcommand.positionals), '');
    if (subcommand.options.length > 0) lines.push(...optionTable(subcommand.options), '');
  }
  const refused = Object.entries(command.refusedOptions ?? {});
  if (refused.length > 0) {
    lines.push(`Refused flags (exit 1): ${refused.map(([name]) => `\`--${name}\``).join(', ')}. ${escapeProse(sentence(refused[0][1]))}`, '');
  }
  lines.push(`Exit codes: ${command.exitCodes.map((exitCode) => `${exitCode} (${getExitCodeInfo(exitCode)?.name ?? 'unknown'})`).join(', ')}.`, '');
  return lines;
}

/**
 * The support matrix for the commands this build has: one row per platform configuration, one column
 * per command. A command the matrix names but the registry does not is left out.
 * @param {readonly CommandSpec[]} commands
 * @param {Record<string, any>} tiers
 * @returns {string[]}
 */
function renderSupportMatrix(commands, tiers) {
  const names = commands.map((command) => command.name).filter((name) => tiers.commands.includes(name));
  const lines = ['## Support tiers', ''];
  lines.push(
    'Before a command runs, the platform gate looks up this machine in `src/core/tiers.json`: the first',
    'matching row wins. `refused` exits 8 before the command starts. `experimental` runs, on a row the',
    'reference measurements do not cover; `setup` asks you to acknowledge it first, or takes',
    '`--experimental` as the acknowledgement. `degraded` runs and names what it cannot measure.',
    '',
  );
  lines.push(`| Platform | ${names.map((name) => `\`${name}\``).join(' | ')} |`, `|---|${names.map(() => '---').join('|')}|`);
  /** @type {Set<string>} */
  const usedReasons = new Set();
  for (const row of tiers.rows) {
    const cells = names.map((name) => {
      const cell = row.tiers[name];
      if (cell.reason && cell.tier === 'refused') usedReasons.add(cell.reason);
      return describeCell(cell);
    });
    lines.push(`| ${escapeCell(escapeProse(row.label))} | ${cells.join(' | ')} |`);
  }
  lines.push('');
  if (usedReasons.size > 0) {
    lines.push('What a refusal prints:', '');
    for (const reason of usedReasons) lines.push(`- \`${reason}\`: ${escapeProse(tiers.reasons[reason])}`);
    lines.push('');
  }
  return lines;
}

/**
 * @param {Record<string, any>} cell
 * @returns {string}
 */
function describeCell(cell) {
  const notes = [];
  if (cell.tier !== 'degraded' && cell.degraded === true) notes.push('degraded');
  if (cell.noShippedPreset === true) notes.push('no shipped preset');
  if (cell.experimentalBackend === true) notes.push('experimental backend');
  if (cell.errorFinding === true) notes.push('reports an ERROR');
  return notes.length === 0 ? cell.tier : `${cell.tier} (${notes.join(', ')})`;
}

/**
 * @param {readonly PositionalSpec[]} positionals
 * @returns {string[]}
 */
function positionalTable(positionals) {
  const rows = ['| Argument | Description |', '|---|---|'];
  for (const positional of positionals) {
    rows.push(`| ${escapeCell(`\`${positionalName(positional)}\``)} | ${escapeCell(escapeProse(positionalDescription(positional)))} |`);
  }
  return rows;
}

/**
 * @param {readonly OptionSpec[]} options
 * @returns {string[]}
 */
function optionTable(options) {
  const rows = ['| Flag | Description |', '|---|---|'];
  for (const option of options) rows.push(`| ${escapeCell(`\`${formatFlag(option)}\``)} | ${escapeCell(escapeProse(describeOption(option)))} |`);
  return rows;
}

/**
 * @param {OptionSpec} option
 * @returns {string}
 */
function formatFlag(option) {
  if (option.type === 'boolean') return `--${option.name}`;
  const valueName = option.choices && option.type !== 'list' ? option.choices.join('|') : (option.valueName ?? 'value');
  return `--${option.name} <${valueName}>`;
}

/**
 * @param {OptionSpec} option
 * @returns {string}
 */
function describeOption(option) {
  const notes = [];
  if (option.required) notes.push('required');
  if (option.type === 'list') notes.push(option.choices ? `comma-separated: ${option.choices.join(', ')}` : 'comma-separated');
  if (option.type === 'variadic') notes.push('takes every value up to the next flag');
  if ((option.type === 'integer' || option.type === 'number') && option.min !== undefined && option.max !== undefined) {
    notes.push(`range ${option.min} to ${option.max}`);
  }
  return notes.length === 0 ? option.description : `${option.description} (${notes.join('; ')})`;
}

/**
 * @param {PositionalSpec} positional
 * @returns {string}
 */
function positionalName(positional) {
  return positional.required ? `<${positional.name}>` : `[${positional.name}]`;
}

/**
 * @param {PositionalSpec} positional
 * @returns {string}
 */
function positionalDescription(positional) {
  return positional.choices ? `${positional.description}: ${positional.choices.join(', ')}` : positional.description;
}

/**
 * @param {string} text
 * @returns {string}
 */
function sentence(text) {
  const trimmed = text.trim();
  const capital = trimmed.charAt(0).toUpperCase() + trimmed.slice(1);
  return /[.!?]$/.test(capital) ? capital : `${capital}.`;
}

/**
 * A pipe splits a table cell even inside inline code, so every pipe in a cell is escaped.
 * @param {string} value
 * @returns {string}
 */
function escapeCell(value) {
  return value.replace(/\|/g, '\\|');
}

/**
 * Angle brackets outside inline code would be read as HTML and disappear, so they are written as
 * entities there and left alone inside backticks.
 * @param {string} text
 * @returns {string}
 */
export function escapeProse(text) {
  return text.split(/(`[^`]*`)/).map((part) => (part.startsWith('`') ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;'))).join('');
}

/**
 * @param {readonly string[]} argv
 * @returns {number}
 */
export function main(argv) {
  const check = argv.includes('--check');
  const rendered = renderCliReference();
  const target = fileURLToPath(OUTPUT_URL);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === rendered) {
    process.stdout.write(`${OUTPUT_NAME} is current (${COMMANDS.length} commands)\n`);
    return 0;
  }
  if (check) {
    process.stderr.write(`${OUTPUT_NAME} differs from the registry; run node scripts/gen-cli-docs.mjs\n`);
    return 1;
  }
  fs.mkdirSync(fileURLToPath(new URL('../docs/', import.meta.url)), { recursive: true });
  fs.writeFileSync(target, rendered);
  process.stdout.write(`${OUTPUT_NAME} written (${COMMANDS.length} commands)\n`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main(process.argv.slice(2));
}
