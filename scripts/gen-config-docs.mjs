#!/usr/bin/env node
// Generates docs/configuration.md from schema/config.schema.json (spec 19, 21.1; build step S19).
//
// The schema is what `config.json` is validated against, so its keys, types, defaults and descriptions
// are the documentation. Nothing is written here by hand: a key the schema does not describe shows a
// dash rather than an invented sentence. CI runs this and fails when the committed page differs.
//
// Exit codes: 0 written or already current, 1 --check found a difference, 2 usage or runtime error.
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SCHEMA_URL = new URL('../schema/config.schema.json', import.meta.url);
export const OUTPUT_URL = new URL('../docs/configuration.md', import.meta.url);
const OUTPUT_NAME = 'docs/configuration.md';

const HEADER = `<!-- Generated by scripts/gen-config-docs.mjs from schema/config.schema.json. Do not edit by hand. -->

# Configuration

\`opencode-unity\` reads \`config.json\` from its home directory: \`%LOCALAPPDATA%\\opencode-unity\` on
Windows, and \`$XDG_DATA_HOME/opencode-unity\` (default \`~/.local/share/opencode-unity\`) elsewhere. The
\`OPENCODE_UNITY_HOME\` environment variable moves the whole home. \`opencode-unity setup\` writes the file
only when it is absent, and never replaces yours.
`;

/**
 * @typedef {object} ConfigRow
 * @property {string} key          Dotted path, for example `guard.maxGpuUtilPercent`.
 * @property {string} type
 * @property {string} defaultValue
 * @property {string} description
 */

/**
 * @param {Record<string, any>} [schema]
 * @returns {string}
 */
export function renderConfigReference(schema = readSchema()) {
  const lines = [HEADER];
  if (typeof schema.description === 'string') lines.push(escapeProse(schema.description), '');
  const topLevel = Object.entries(schema.properties ?? {});
  const scalars = topLevel.filter(([, property]) => !hasNestedRows(resolve(schema, property), schema));
  if (scalars.length > 0) {
    lines.push('## Top-level keys', '');
    lines.push(...table(scalars.flatMap(([name, property]) => collectRows(schema, name, property))), '');
  }
  for (const [name, property] of topLevel.filter(([, candidate]) => hasNestedRows(resolve(schema, candidate), schema))) {
    lines.push(`## ${name}`, '');
    const description = describe(schema, property);
    if (description !== '') lines.push(escapeProse(description), '');
    lines.push(...table(collectRows(schema, name, property)), '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/**
 * @returns {Record<string, any>}
 */
export function readSchema() {
  return JSON.parse(fs.readFileSync(SCHEMA_URL, 'utf8'));
}

/**
 * Every documented leaf below `key`. An object with named properties is expanded; an object keyed by
 * ids (`additionalProperties` with a schema) is expanded under a `<id>` placeholder; everything else is
 * one row.
 * A default stated on an object reaches the keys below it, so `budget.prefixTargetTokens.unity-code`
 * shows the value its parent's default gives it.
 * @param {Record<string, any>} root
 * @param {string} key
 * @param {Record<string, any>} property
 * @param {{ value: unknown } | null} [inherited]  The default the parent's default gives this key.
 * @returns {ConfigRow[]}
 */
export function collectRows(root, key, property, inherited = null) {
  const resolved = resolve(root, property);
  const own = findDefault(property, resolved) ?? inherited;
  if (resolved.properties && typeof resolved.properties === 'object') {
    return Object.entries(resolved.properties).flatMap(([name, child]) => collectRows(root, `${key}.${name}`, child, childDefault(own, name)));
  }
  if (isKeyedObject(resolved)) {
    const placeholder = keyPlaceholder(key);
    return collectRows(root, `${key}.${placeholder}`, resolved.additionalProperties);
  }
  return [{ key, type: describeType(root, resolved), defaultValue: own === null ? '-' : `\`${JSON.stringify(own.value)}\``, description: describe(root, property) }];
}

/**
 * @param {Record<string, any>} property
 * @param {Record<string, any>} resolved
 * @returns {{ value: unknown } | null}
 */
function findDefault(property, resolved) {
  if (Object.hasOwn(property, 'default')) return { value: property.default };
  if (Object.hasOwn(resolved, 'default')) return { value: resolved.default };
  return null;
}

/**
 * @param {{ value: unknown } | null} parent
 * @param {string} name
 * @returns {{ value: unknown } | null}
 */
function childDefault(parent, name) {
  const value = parent?.value;
  if (value === null || typeof value !== 'object' || Array.isArray(value) || !Object.hasOwn(value, name)) return null;
  return { value: /** @type {Record<string, unknown>} */ (value)[name] };
}

/**
 * @param {Record<string, any>} schema
 * @param {Record<string, any>} root
 * @returns {boolean}
 */
function hasNestedRows(schema, root) {
  if (schema.properties && typeof schema.properties === 'object') return true;
  return isKeyedObject(schema) && hasNestedRows(resolve(root, schema.additionalProperties), root);
}

/**
 * @param {Record<string, any>} schema
 * @returns {boolean}
 */
function isKeyedObject(schema) {
  return schema.type === 'object' && typeof schema.additionalProperties === 'object' && schema.additionalProperties !== null;
}

/**
 * @param {string} key
 * @returns {string}
 */
function keyPlaceholder(key) {
  return key === 'projects' ? '<project-id>' : '<id>';
}

/**
 * A property with a `$ref` takes the referenced definition, with its own keywords laid over it.
 * @param {Record<string, any>} root
 * @param {Record<string, any>} property
 * @returns {Record<string, any>}
 */
export function resolve(root, property) {
  if (typeof property?.$ref !== 'string') return property ?? {};
  const match = /^#\/\$defs\/(.+)$/.exec(property.$ref);
  if (match === null || root.$defs?.[match[1]] === undefined) throw new Error(`Unresolvable $ref ${property.$ref}`);
  const { $ref, ...rest } = property;
  return { ...resolve(root, root.$defs[match[1]]), ...rest };
}

/**
 * @param {Record<string, any>} root
 * @param {Record<string, any>} property
 * @returns {string}
 */
function describe(root, property) {
  const own = typeof property.description === 'string' ? property.description : null;
  const resolved = resolve(root, property);
  return own ?? (typeof resolved.description === 'string' ? resolved.description : '');
}

/**
 * @param {Record<string, any>} root
 * @param {Record<string, any>} schema
 * @returns {string}
 */
export function describeType(root, schema) {
  if (Object.hasOwn(schema, 'const')) return `\`${JSON.stringify(schema.const)}\` (fixed)`;
  if (Array.isArray(schema.enum)) return `one of ${schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(', ')}`;
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map((alternative) => describeType(root, resolve(root, alternative))).join(', or ');
  const types = Array.isArray(schema.type) ? schema.type : [schema.type ?? 'any'];
  const base = types.map((type) => (type === 'array' ? describeArray(root, schema) : type)).join(' or ');
  const range = describeRange(schema);
  return range === '' ? base : `${base} (${range})`;
}

/**
 * @param {Record<string, any>} root
 * @param {Record<string, any>} schema
 * @returns {string}
 */
function describeArray(root, schema) {
  const itemType = schema.items ? describeType(root, resolve(root, schema.items)) : 'any';
  // "array of strings", but "array of one of `a`, `b`" and "array of numbers (above 0, at most 10)".
  const items = itemType.replace(/^(string|number|integer|boolean|object)\b/, '$1s');
  const { minItems, maxItems } = schema;
  const size = minItems !== undefined && minItems === maxItems ? `exactly ${minItems} ` : minItems === 1 ? 'one or more ' : minItems ? `at least ${minItems} ` : '';
  return `array of ${size}${items}`;
}

/**
 * @param {Record<string, any>} schema
 * @returns {string}
 */
function describeRange(schema) {
  const low = schema.exclusiveMinimum !== undefined ? `above ${schema.exclusiveMinimum}` : schema.minimum !== undefined ? `${schema.minimum}` : null;
  const high = schema.maximum !== undefined ? `${schema.maximum}` : null;
  if (low !== null && high !== null) return schema.exclusiveMinimum !== undefined ? `${low}, at most ${high}` : `${low} to ${high}`;
  if (low !== null) return schema.exclusiveMinimum !== undefined ? low : `at least ${low}`;
  if (high !== null) return `at most ${high}`;
  return '';
}

/**
 * @param {ConfigRow[]} rows
 * @returns {string[]}
 */
function table(rows) {
  return [
    '| Key | Type | Default | Description |',
    '|---|---|---|---|',
    ...rows.map((row) => `| ${escapeCell(`\`${row.key}\``)} | ${escapeCell(row.type)} | ${escapeCell(row.defaultValue)} | ${escapeCell(escapeProse(row.description || '-'))} |`),
  ];
}

/**
 * A pipe splits a table cell even inside inline code, so every pipe in a cell is escaped.
 * @param {string} value
 * @returns {string}
 */
function escapeCell(value) {
  return value.replace(/\|/g, '\\|');
}

/**
 * Angle brackets outside inline code would be read as HTML and disappear, so `<home>` in a schema
 * description is written as an entity there and left alone inside backticks.
 * @param {string} text
 * @returns {string}
 */
export function escapeProse(text) {
  return text.split(/(`[^`]*`)/).map((part) => (part.startsWith('`') ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;'))).join('');
}

/**
 * @param {readonly string[]} argv
 * @returns {number}
 */
export function main(argv) {
  const check = argv.includes('--check');
  const rendered = renderConfigReference();
  const target = fileURLToPath(OUTPUT_URL);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === rendered) {
    process.stdout.write(`${OUTPUT_NAME} is current\n`);
    return 0;
  }
  if (check) {
    process.stderr.write(`${OUTPUT_NAME} differs from the schema; run node scripts/gen-config-docs.mjs\n`);
    return 1;
  }
  fs.mkdirSync(fileURLToPath(new URL('../docs/', import.meta.url)), { recursive: true });
  fs.writeFileSync(target, rendered);
  process.stdout.write(`${OUTPUT_NAME} written\n`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main(process.argv.slice(2));
}
