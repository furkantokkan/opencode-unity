#!/usr/bin/env node
// Generates docs/doctor-checks.md from the check registry (spec 19, 21.1).
//
// The registry is the only source: the page, the `--explain` text and the run order all read the same
// list, so a check cannot be documented differently from how it behaves, and a new check cannot be
// added without its page entry. CI runs this and fails when the committed page differs.
//
// Exit codes: 0 written or already current, 1 --check found a difference, 2 usage or runtime error.
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { CHECK_GROUPS } from '../src/doctor/engine.js';
import { SEVERITY_LABELS } from '../src/doctor/finding.js';
import { CHECKS, validateRegistry } from '../src/doctor/checks/index.js';

export const OUTPUT_URL = new URL('../docs/doctor-checks.md', import.meta.url);

const HEADER = `<!-- Generated by scripts/gen-doctor-docs.mjs from src/doctor/checks/. Do not edit by hand. -->

# Doctor checks

\`opencode-unity doctor\` runs the checks below. Each one has a stable id: \`doctor --explain <id>\` prints
the same rationale at the terminal, and \`doctor --json\` reports every id with its outcome.

Severity is what a check reports when it finds something. A check that finds nothing reports \`ok\`, and a
check whose subject is absent reports \`skipped\` with the reason. Before \`opencode-unity setup\` has run on
a machine there is no configuration to be wrong, so a check that would report \`ERROR\` about this
product's own configuration reports \`WARN\` instead and says so; \`--strict\` still fails on it.

Exit codes: \`0\` with no errors, \`5\` with at least one error, or with at least one warning under
\`--strict\`.
`;

/**
 * @param {readonly import('../src/doctor/engine.js').CheckSpec[]} [checks]
 * @param {readonly { id: string, label: string }[]} [groups]
 * @returns {string}
 */
export function renderDoctorChecks(checks = CHECKS, groups = CHECK_GROUPS) {
  const problems = validateRegistry(checks, groups.map((group) => group.id));
  if (problems.length > 0) throw new Error(`The check registry is invalid:\n  ${problems.join('\n  ')}`);
  const sections = groups
    .map((group) => ({ group, entries: checks.filter((check) => check.group === group.id) }))
    .filter((section) => section.entries.length > 0);
  const lines = [HEADER, `Checks in this build: ${checks.length}.`, ''];
  for (const { group, entries } of sections) {
    lines.push(`## ${group.label}`, '');
    lines.push('| Check | Reports | What it detects, and why it matters |', '|---|---|---|');
    for (const check of entries) {
      lines.push(`| \`${check.id}\` | ${severityRange(check)} | ${escapeCell(check.why)} |`);
    }
    lines.push('');
    for (const check of entries) {
      lines.push(`### \`${check.id}\` — ${check.title}`, '');
      lines.push(`- Reports: ${severityRange(check)}`);
      lines.push(`- Fix: ${check.fix}`);
      lines.push(`- Source: ${check.source}`);
      if (check.alwaysSevere === true) lines.push('- Keeps its severity even before this product is set up on the machine.');
      lines.push('');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/**
 * @param {import('../src/doctor/engine.js').CheckSpec} check
 * @returns {string}
 */
function severityRange(check) {
  return check.severities.map((severity) => SEVERITY_LABELS[severity]).join(' / ');
}

/**
 * @param {string} value
 * @returns {string}
 */
function escapeCell(value) {
  return value.replace(/\|/g, '\\|');
}

/**
 * @param {readonly string[]} argv
 * @returns {number}
 */
export function main(argv) {
  const check = argv.includes('--check');
  const rendered = renderDoctorChecks();
  const target = fileURLToPath(OUTPUT_URL);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === rendered) {
    process.stdout.write(`docs/doctor-checks.md is current (${CHECKS.length} checks)\n`);
    return 0;
  }
  if (check) {
    process.stderr.write('docs/doctor-checks.md differs from the registry; run node scripts/gen-doctor-docs.mjs\n');
    return 1;
  }
  fs.mkdirSync(fileURLToPath(new URL('../docs/', import.meta.url)), { recursive: true });
  fs.writeFileSync(target, rendered);
  process.stdout.write(`docs/doctor-checks.md written (${CHECKS.length} checks)\n`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main(process.argv.slice(2));
}
